""""
Task: Virat ke runs = 120, Rohit ke runs = 95.

Total runs print karo.

Check karo kya Virat > Rohit.
"""

virat_runs = 120
rohit_runs = 95
total_runs = virat_runs + rohit_runs
print(f"Total runs: {total_runs}")

if virat_runs > rohit_runs:
    print("Virat has more runs than Rohit.")
else:
    print("Rohit has more runs than Virat.")