## example
print("Hello, World!")
numbers = [1, 2, 3, 4, 5]
print(f"The sum of the numbers is: {sum(numbers)}") ## f is used to format the string and display the sum of the numbers in the list.
print(f"The maximum number in the list is: {max(numbers)}") ## f is used to format the string and display the maximum number in the list.
print(f"the minimum number inthe list is: {min(numbers)}") ## f is used to format the string and display the minimum number in the list.
print(f"the lengfth of the list is.: {len(numbers)}") ## f is used to format the string and display the length of the list.
print(f" the sorted list is: {sorted(numbers)}") ## f is used to format the string and display the sorted list.
print(f"the type of the list is: {type(numbers)}") ## f is used to format the string and display the type of the list.




